export type I18nDict = typeof zh;

export interface LocaleDefinition {
  id: string;
  nativeName: string;
  shortLabel: string;
  dict: I18nDict;
}

const localeRegistry = new Map<string, LocaleDefinition>([
  ['zh', { id: 'zh', nativeName: '简体中文', shortLabel: '中文', dict: zh }],
  ['en', { id: 'en', nativeName: 'English', shortLabel: 'EN', dict: en }],
]);

/**
 * Community extension hook: register additional locales (e.g. 'ja', 'ko')
 * with automatic fallback to English/Chinese for any untranslated keys.
 */
export function registerLocale(
  id: string,
  nativeName: string,
  shortLabel: string,
  partial: Partial<I18nDict>,
): void {
  const key = id.toLowerCase();
  localeRegistry.set(key, {
    id: key,
    nativeName,
    shortLabel,
    dict: { ...en, ...partial },
  });
}

export function listLocales(): LocaleDefinition[] {
  return Array.from(localeRegistry.values());
}

export function normalizeLang(raw?: string | null): Lang {
  if (!raw) return 'zh';
  const lower = raw.toLowerCase();
  if (localeRegistry.has(lower)) return lower;
  const primary = lower.split('-')[0];
  if (localeRegistry.has(primary)) return primary;
  return 'zh';
}

export function getDict(lang: Lang): I18nDict {
  const key = normalizeLang(lang);
  return localeRegistry.get(key)?.dict ?? zh;
}

/**
 * Template interpolation helper: fmt("Loaded {loaded} / {total}", { loaded: 60, total: 2143 })
 */
export function fmt(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? String(params[k]) : `{${k}}`));
}
